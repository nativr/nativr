import { createHash } from "node:crypto";
import { mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const lapackRoot = requiredDirectory("NATIVR_LAPACK_SOURCE");
const f2c = requiredExecutable("F2C");
const emcc = requiredExecutable("EMCC");
const f2cInclude = requiredDirectory("F2C_INCLUDE");
const output = path.join(root, "packages", "nativr", "src", "lapack-dsyevr-bytes.ts");
const buildRoot = await mkdtemp(path.join(os.tmpdir(), "nativr-lapack-dsyevr-"));
const supportNames = new Set([
  "DISNAN",
  "DLAISNAN",
  "DLAMCH",
  "DLASSQ",
  "DNRM2",
  "IPARAM2STAGE",
  "XERBLA",
]);

try {
  const sourceFiles = await sourceIndex(lapackRoot);
  const selected = new Map();
  const pending = ["DSYEVR"];
  while (pending.length > 0) {
    const name = pending.pop();
    if (selected.has(name) || supportNames.has(name)) continue;
    const file = sourceFiles.get(name);
    if (file === undefined) throw new Error(`Missing LAPACK source routine ${name}.`);
    if (path.extname(file).toLowerCase() !== ".f") {
      throw new Error(`Routine ${name} is not fixed-form f2c input: ${file}`);
    }
    selected.set(name, file);
    for (const dependency of await dependencies(file)) {
      if (!selected.has(dependency) && !supportNames.has(dependency)) pending.push(dependency);
    }
  }

  const generated = [];
  for (const [name, source] of [...selected].sort(([left], [right]) => left.localeCompare(right))) {
    let text = await readFile(source, "utf8");
    if (name === "DLARFT") {
      text = text
        .replaceAll("RECURSIVE SUBROUTINE DLARFT", "SUBROUTINE DLARFT")
        .replaceAll("END SUBROUTINE", "END");
    }
    const fortran = path.join(buildRoot, `${name.toLowerCase()}.f`);
    await writeFile(fortran, text, "utf8");
    run(f2c, ["-A", "-R", path.basename(fortran)], buildRoot);
    generated.push(path.join(buildRoot, `${name.toLowerCase()}.c`));
  }

  const wrapper = path.join(buildRoot, "dsyevr.mjs");
  run(
    emcc,
    [
      ...generated,
      path.join(root, "scripts", "lapack-dsyevr-support.c"),
      `-I${f2cInclude}`,
      "-Wno-shift-op-parentheses",
      "-O2",
      "--no-entry",
      "-sMODULARIZE=1",
      "-sEXPORT_ES6=1",
      "-sENVIRONMENT=web,worker,node",
      "-sFILESYSTEM=0",
      "-sALLOW_MEMORY_GROWTH=1",
      "-sINITIAL_HEAP=1048576",
      "-sEXPORTED_FUNCTIONS=_dsyevr_,_malloc,_free",
      "-o",
      wrapper,
    ],
    buildRoot,
  );
  const wasm = await readFile(path.join(buildRoot, "dsyevr.wasm"));
  const module = new WebAssembly.Module(wasm);
  const imports = WebAssembly.Module.imports(module);
  if (
    imports.length !== 1 ||
    imports[0]?.module !== "env" ||
    imports[0]?.name !== "emscripten_resize_heap" ||
    imports[0]?.kind !== "function"
  ) {
    throw new Error(`Unexpected DSYEVR Wasm imports: ${JSON.stringify(imports)}`);
  }
  const hash = createHash("sha256").update(wasm).digest("hex");
  const encoded = wasm.toString("base64");
  await writeFile(
    output,
    `// Generated by scripts/build-lapack-dsyevr.mjs from LAPACK 3.12.1.\n` +
      `// SHA-256: ${hash}\n` +
      `export const LAPACK_DSYEVR_WASM_SHA256 = ${JSON.stringify(hash)};\n` +
      `export const LAPACK_DSYEVR_WASM_BASE64 = ${JSON.stringify(encoded)};\n`,
    "utf8",
  );
  console.log(`Built ${path.relative(root, output)} (${wasm.length} Wasm bytes, SHA-256 ${hash}).`);
} finally {
  await rm(buildRoot, { recursive: true, force: true });
}

async function sourceIndex(base) {
  const result = new Map();
  for (const relative of ["SRC", "BLAS/SRC", "INSTALL"]) {
    const directory = path.join(base, relative);
    for (const entry of await readdir(directory)) {
      if (!/\.(?:f|F|f90)$/i.test(entry)) continue;
      const name = path.basename(entry, path.extname(entry)).toUpperCase();
      if (!result.has(name)) result.set(name, path.join(directory, entry));
    }
  }
  return result;
}

async function dependencies(file) {
  const result = new Set();
  for (const statement of fortranStatements(await readFile(file, "utf8"))) {
    for (const match of statement.toUpperCase().matchAll(/\bCALL\s+([A-Z][A-Z0-9_]*)/g)) {
      result.add(match[1]);
    }
    const external = statement.toUpperCase().match(/^\s*EXTERNAL\s+(.+)$/);
    if (external !== null) {
      for (const name of external[1].match(/[A-Z][A-Z0-9_]*/g) ?? []) result.add(name);
    }
  }
  return result;
}

function fortranStatements(source) {
  const result = [];
  let current = "";
  for (const raw of source.split(/\r?\n/)) {
    if (/^[cC*!]/.test(raw)) continue;
    const line = raw.padEnd(6);
    const continuation = line[5] !== " " && line[5] !== "0";
    const body = line.slice(6, 72).replace(/!.*/, "").trim();
    if (body.length === 0) continue;
    if (continuation) current += ` ${body}`;
    else {
      if (current.length > 0) result.push(current);
      current = body;
    }
  }
  if (current.length > 0) result.push(current);
  return result;
}

function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, encoding: "utf8", stdio: "pipe" });
  if (result.status !== 0) {
    throw new Error(
      `${command} failed (${result.status ?? "no status"}):\n${result.stdout}\n${result.stderr}`,
    );
  }
}

function requiredDirectory(name) {
  const value = process.env[name];
  if (value === undefined || value.length === 0)
    throw new Error(`${name} must name a local directory.`);
  return path.resolve(value);
}

function requiredExecutable(name) {
  const value = process.env[name];
  if (value === undefined || value.length === 0)
    throw new Error(`${name} must name a local executable.`);
  return path.resolve(value);
}
