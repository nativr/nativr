import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";
import prettierOptions from "../prettier.config.mjs";

const surface = JSON.parse(
  await readFile(new URL("../compatibility/gnu-r/surface.json", import.meta.url), "utf8"),
);
const manifest = JSON.parse(
  await readFile(new URL("../docs/compatibility-manifest.json", import.meta.url), "utf8"),
);
const supported = new Set(manifest.packages.flatMap((pkg) => pkg.functions.map((fn) => fn.name)));
const base = new Set(
  surface.packages.find((pkg) => pkg.name === "base").exports.map((entry) => entry.name),
);
const owners = {};
for (const name of [...supported].sort()) {
  if (base.has(name)) continue;
  const candidates = surface.packages.filter(
    (pkg) =>
      pkg.name !== "base" && pkg.exports.some((entry) => entry.name === name && entry.callable),
  );
  if (candidates.length === 1) owners[name] = candidates[0].name;
}
const target = new URL("../packages/base/src/builtin-package-owners.ts", import.meta.url);
const expected = await format(
  `// Generated by scripts/builtin-package-owners.mjs from the clean-room GNU R 4.6.1 public export inventory.\n// No implementation bodies are collected or used.\nexport const BUILTIN_PACKAGE_OWNERS: Readonly<Record<string, string>> = ${JSON.stringify(owners)};\n`,
  { ...prettierOptions, parser: "typescript" },
);
if (process.argv.includes("--check") || new URL(import.meta.url).searchParams.has("check")) {
  if ((await readFile(target, "utf8")) !== expected)
    throw new Error(
      "Builtin package ownership is stale. Run node scripts/builtin-package-owners.mjs.",
    );
  console.log(`Verified ${Object.keys(owners).length} public builtin package owners.`);
} else {
  await writeFile(target, expected);
}
